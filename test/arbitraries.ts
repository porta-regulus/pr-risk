// fast-check generator of valid native documents (AT-1, SPEC.md Sec. 12.1).
import fc from 'fast-check';
import type { Distribution, Risk, RiskDocument } from '../src/schema';

const text = fc.string({ unit: 'grapheme', maxLength: 40 });
const nonEmpty = fc.string({ unit: 'grapheme', minLength: 1, maxLength: 40 });
const NEGATIVE = ['Accept', 'Avoid', 'Transfer', 'Mitigate'] as const;
const POSITIVE = ['Realize', 'Share', 'Enhance', 'Accept'] as const;
const STATUS = ['Open', 'In treatment', 'Monitored', 'Accepted', 'Review needed', 'Closed'] as const;
const CATEGORY = ['ict', 'financial', 'legal', 'operational', 'strategic', 'safety', 'reputation'] as const;
const METHODS = ['qualitative', 'semi-quantitative', 'quantitative'] as const;

const positive = (max: number) => fc.double({ min: 1e-6, max, noNaN: true, noDefaultInfinity: true });

const distribution = (max: number): fc.Arbitrary<Distribution> =>
  fc.oneof(
    fc.tuple(positive(max), positive(max)).filter(([a, b]) => a !== b).map(([a, b]) => ({
      type: 'lognormal' as const,
      lower: Math.min(a, b),
      upper: Math.max(a, b),
      confidence: 0.9 as const,
    })),
    fc.tuple(positive(max), positive(max), positive(max)).map((values) => {
      const [min, mode, max_] = [...values].sort((a, b) => a - b) as [number, number, number];
      return { type: 'pert' as const, min, mode, max: max_ };
    }),
    positive(max).map((value) => ({ type: 'constant' as const, value })),
  );

const riskArbitrary = (index: number, registerIds: readonly string[], quantitative: ReadonlySet<string>) =>
  fc
    .record({
      registerId: fc.constantFrom(...registerIds),
      polarity: fc.constantFrom('negative' as const, 'positive' as const),
      pick: fc.uniqueArray(fc.nat({ max: 3 }), { minLength: 1, maxLength: 4 }),
      riskDescription: nonEmpty,
      riskCategory: nonEmpty,
      riskLikelihood: fc.double({ min: 0, max: 1, noNaN: true }),
      riskImpact: fc.integer({ min: 0, max: 10_000_000 }),
      riskResponseCost: fc.integer({ min: 0, max: 1_000_000 }),
      riskResponseDescription: text,
      riskOwnerPointOfContact: nonEmpty,
      status: fc.constantFrom(...STATUS),
      code: fc.constantFrom(...CATEGORY),
      pending: fc.boolean(),
      frequency: distribution(100),
      impactPerEvent: distribution(10_000_000),
      detail: fc.option(fc.record({ systemAffected: text, threatEvents: text, comments: text }, { requiredKeys: [] }), { nil: undefined }),
    })
    .map((item): Risk => {
      const types = item.polarity === 'negative' ? NEGATIVE : POSITIVE;
      const risk: Record<string, unknown> = {
        riskId: `K-${String(index)}`,
        riskDescription: item.riskDescription,
        riskCategory: item.riskCategory,
        riskLikelihood: item.riskLikelihood,
        riskImpact: item.riskImpact,
        exposureRating: Math.round(item.riskLikelihood * item.riskImpact),
        riskResponseType: item.pending ? ['Accept'] : item.pick.map((i) => types[i] ?? 'Accept').filter((type, i, all) => all.indexOf(type) === i),
        riskResponseCost: item.pending ? 0 : item.riskResponseCost,
        riskResponseDescription: item.riskResponseDescription,
        riskOwnerPointOfContact: item.riskOwnerPointOfContact,
        status: item.status,
        registerId: item.registerId,
        polarity: item.polarity,
        category: { code: item.code },
        responseDecision: item.pending ? 'pending' : 'decided',
      };
      if (quantitative.has(item.registerId)) {
        risk['estimate'] = { frequency: item.frequency, impactPerEvent: item.impactPerEvent, method: 'expert-calibrated', rationale: 'generated by the AT-1 test' };
      }
      if (item.detail !== undefined) risk['detail'] = item.detail;
      return risk as unknown as Risk;
    });

export const documentArbitrary: fc.Arbitrary<RiskDocument> = fc
  .record({
    methods: fc.array(fc.constantFrom(...METHODS), { minLength: 1, maxLength: 3 }),
    riskCount: fc.integer({ min: 1, max: 6 }),
    title: nonEmpty,
    organization: fc.option(text, { nil: undefined }),
    timeframe: fc.integer({ min: 1, max: 60 }),
    simulation: fc.option(fc.record({ seed: fc.nat(), trials: fc.integer({ min: 1000, max: 1_000_000 }) }), { nil: undefined }),
  })
  .chain((base) => {
    const registers = base.methods.map((method, index) => ({
      id: `REG-${String(index)}`,
      title: `Register ${String(index)}`,
      level: 'system' as const,
      timeframeMonths: base.timeframe,
      asOf: '2026-10-27',
      method,
    }));
    const quantitative = new Set(registers.filter((register) => register.method === 'quantitative').map((register) => register.id));
    const ids = registers.map((register) => register.id);
    return fc.tuple(...Array.from({ length: base.riskCount }, (_, index) => riskArbitrary(index, ids, quantitative))).map((risks) => {
      const doc: Record<string, unknown> = {
        schemaVersion: '1.0.0',
        document: { id: 'AT1', title: base.title, currency: 'EUR', createdOn: '2026-10-27T00:00:00Z', ...(base.organization === undefined ? {} : { organization: base.organization }) },
        registers,
        risks,
      };
      if (base.simulation !== undefined) doc['simulation'] = { ...base.simulation, engineVersion: '0.0.0' };
      return doc as unknown as RiskDocument;
    });
  });
