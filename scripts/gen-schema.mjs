// Generate src/schema/generated/ from docs/schema (build task 2).
//
// 1. validators.js. Ajv 2020 standalone code for our schema and the two vendored
//    NIST IR 8286 Rev. 1 schemas. The app never compiles a schema at run time,
//    because Ajv compiles with new Function (ADR-0004 E1).
// 2. types.ts. TypeScript types from our schema.
//
// Usage: node scripts/gen-schema.mjs          write the files
//        node scripts/gen-schema.mjs --check  fail if the files are out of date
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (path) => JSON.parse(readFileSync(root + path, 'utf8'));
const OURS = read('docs/schema/risk-register.schema.json');
const NIST_REGISTER = read('docs/schema/vendor/nist-ir8286r1/risk_register_schema.json');
const NIST_RDR = read('docs/schema/vendor/nist-ir8286r1/risk_detail_record_schema.json');
const OUT = 'src/schema/generated/';
const BANNER = '// Generated by scripts/gen-schema.mjs from docs/schema. Do not edit.\n';

// Formats are annotations only, as in docs/schema/validate.py (jsonschema without a
// format checker). Both validators must give the same verdict (AT-1).
const ajv = new Ajv2020({
  code: { source: true, esm: true },
  // Shared definitions become functions, not inlined copies. This keeps the code small.
  inlineRefs: false,
  allErrors: true,
  validateFormats: false,
  strict: true,
  // Valid patterns that strict mode flags. "required" inside "not" and "anyOf"
  // without "properties", and "items" inside "if"/"then" without "type".
  strictRequired: false,
  strictTypes: false,
  schemas: [NIST_REGISTER, NIST_RDR, OURS],
});

// Ajv 8 emits require() for its runtime helpers even in ESM mode. Make them imports.
const standalone = standaloneCode(ajv, {
  validateDocument: OURS.$id,
  validateNistRegisterEntry: NIST_REGISTER.$id,
  validateNistRdr: NIST_RDR.$id,
}).replace(
  /const (\w+) = require\("([^"]+)"\)\.default;/g,
  (_match, name, module) => `import ${name}Module from "${module}.js";\nconst ${name} = ${name}Module.default ?? ${name}Module;`,
);
if (standalone.includes('require(')) throw new Error('The standalone code still calls require()');
const validators = BANNER + '/* eslint-disable */\n// @ts-nocheck\n' + standalone;

const validatorTypes = `${BANNER}import type { ErrorObject } from 'ajv';

export interface StandaloneValidator {
  (data: unknown): boolean;
  errors?: ErrorObject[] | null;
}

export declare const validateDocument: StandaloneValidator;
export declare const validateNistRegisterEntry: StandaloneValidator;
export declare const validateNistRdr: StandaloneValidator;
`;

// The type generator must not fetch the NIST $id URLs. It reads the vendored copies.
const vendored = { [NIST_REGISTER.$id]: NIST_REGISTER, [NIST_RDR.$id]: NIST_RDR };
const types = await compile(structuredClone(OURS), 'RiskRegisterDocument', {
  bannerComment: BANNER.trim(),
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  $refOptions: {
    resolve: {
      http: false,
      vendored: {
        order: 1,
        canRead: (file) => file.url in vendored,
        read: (file) => JSON.stringify(vendored[file.url]),
      },
    },
  },
});

const files = {
  'validators.js': validators,
  'validators.d.ts': validatorTypes,
  'types.ts': types,
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([name, text]) => {
    try {
      return readFileSync(root + OUT + name, 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(`Out of date: ${stale.map(([name]) => OUT + name).join(', ')}. Run npm run gen:schema.`);
    process.exit(1);
  }
  console.log('Generated schema files are up to date.');
} else {
  mkdirSync(root + OUT, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(root + OUT + name, text);
  console.log(`Wrote ${Object.keys(files).map((name) => OUT + name).join(', ')}`);
}
